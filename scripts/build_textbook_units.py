EXACT = {"각": ["9수03-01"], "각의 뜻과 성질": ["9수03-01"]}


def guess(title, valid):
    if title in EXACT:
        return EXACT[title]
    if title.startswith("점, 선, 면, 각"):
        return ["9수03-01"]
    for keys, codes in RULES:
        if any(k in title for k in keys):
            return [c for c in codes if c in valid]
    return []


def main():
    std_path, out = sys.argv[1:3]
    valid = {s["code"] for s in json.load(open(std_path, encoding="utf-8"))["standards"]}
    result = {"grade": 1, "note": "교과서 차례는 PDF 앞부분 텍스트에서 정리. 소단원-성취기준 연결은 키워드 기반 잠정(mappingConfirmed=false).", "books": {}}
    for key, b in BOOKS.items():
        units = []
        for utitle, domain, subs in b["units"]:
            sublist = []
            for i, (st, page) in enumerate(subs):
                sublist.append({"title": st, "startPage": page, "standards": guess(st, valid)})
            units.append({"title": utitle, "domain": domain, "subUnits": sublist})
        entry = {k: v for k, v in b.items() if k != "units"}
        entry["units"] = units
        entry["mappingConfirmed"] = False
        result["books"][key] = entry
    with open(out, "w", encoding="utf-8") as w:
        json.dump(result, w, ensure_ascii=False, indent=2)
    unmapped = [(k, s["title"]) for k, b in result["books"].items() for u in b["units"] for s in u["subUnits"] if not s["standards"]]
    print("books:", len(result["books"]), "unmapped subunits:", unmapped)
    covered = {c for b in result["books"].values() for u in b["units"] for s in u["subUnits"] for c in s["standards"]}
    print("covered:", sorted(covered))


if __name__ == "__main__":
    main()
